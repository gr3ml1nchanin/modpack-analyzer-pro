  let current = localStorage.getItem('app.lang') || 'ru';
  if (!STRINGS[current]) current = 'ru';
  const listeners = [];

  function t(key, vars) {
    const dict = STRINGS[current] || STRINGS.ru;
    let s = dict[key];
    if (s == null) s = STRINGS.ru[key];
    if (s == null) s = key;
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      }
    }
    return s;
  }

  function setLang(lang) {
    if (!STRINGS[lang] || lang === current) return;
    current = lang;
    localStorage.setItem('app.lang', lang);
    listeners.forEach(fn => { try { fn(lang); } catch (e) { console.error(e); } });
    if (window.Sidebar)   window.Sidebar.render();
    if (window.StatusBar) window.StatusBar.render();
    if (window.TitleBar)  window.TitleBar.render();
    if (window.Router && window.Router.current()) {
      window.Router.go(window.Router.current());
    }
    if (window.Toast) window.Toast.info(t('about.language.label'), lang.toUpperCase());
  }

  function getLang() { return current; }
  function sub(fn) {
    listeners.push(fn);
    return () => { const i = listeners.indexOf(fn); if (i >= 0) listeners.splice(i, 1); };
  }

  return { t, setLang, getLang, sub, langs: Object.keys(STRINGS) };
