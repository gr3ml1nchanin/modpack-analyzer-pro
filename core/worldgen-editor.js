'use strict';
const fsp = require('fs').promises;
const path = require('path');
const log = require('./logger');

/**
 * Сохраняет изменения в виде датапака.
 * changes: массив объектов { id, structures }
 */
async function saveWorldgen(root, changes) {
  const dpName = 'KatAnWorldgen';
  const dpDir = path.join(root, 'datapacks', dpName);

  try {
    // 1. Создаем базовую структуру датапака
    await fsp.mkdir(dpDir, { recursive: true });

    const mcmeta = {
      pack: {
        pack_format: 15, // Стандарт для 1.20.1
        description: 'Worldgen overrides generated by KatAn'
      }
    };
    await fsp.writeFile(path.join(dpDir, 'pack.mcmeta'), JSON.stringify(mcmeta, null, 2), 'utf8');

    // 2. Пишем измененные файлы
    let applied = 0;
    for (const ch of changes) {
      const [ns, name] = ch.id.split(':');
      const dir = path.join(dpDir, 'data', ns, 'worldgen', 'structure_set');
      
      await fsp.mkdir(dir, { recursive: true });

      // Берем оригинальный JSON и подменяем в нем структуры
      const newJson = ch.raw || {};
      newJson.structures = ch.structures.map(s => ({
        structure: s.structure,
        weight: s.weight,
        frequency: s.frequency
      }));

      const filePath = path.join(dir, name + '.json');
      await fsp.writeFile(filePath, JSON.stringify(newJson, null, 2), 'utf8');
      applied++;
    }

    log.info('worldgen-editor', `Создан датапак с ${applied} изменениями`);
    return { ok: true, applied, path: dpDir };
  } catch (err) {
    log.error('worldgen-editor', 'Ошибка сохранения', err.message);
    return { ok: false, error: err.message };
  }
}

module.exports = { saveWorldgen };