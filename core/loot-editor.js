'use strict';
const fsp  = require('fs').promises;
const path = require('path');
const log  = require('./logger');

const OVERRIDES   = 'data/loot-overrides.json';
const KUBEJS_FILE = 'kubejs/server_scripts/analyzer_loot.js';
const KUBEJS_RM   = 'kubejs/server_scripts/README.md';

async function checkLootJS(root) {
  try {
    const mods = await fsp.readdir(path.join(root, 'mods'));
    return mods.some(f => /lootjs/i.test(f));
  } catch { return false; }
}

async function loadOverrides(root) {
  try {
    return JSON.parse(await fsp.readFile(path.join(root, OVERRIDES), 'utf8'));
  } catch {
    return { tables: {} };
  }
}

async function saveOverrides(root, data) {
  const p = path.join(root, OVERRIDES);
  await fsp.mkdir(path.dirname(p), { recursive: true });
  await fsp.writeFile(p, JSON.stringify(data, null, 2), 'utf8');
}

/**
 * tableOverride: {
 *   tableId:     'minecraft:blocks/stone',
 *   category:    'block' | 'entity',
 *   removeEntries: ['minecraft:cobblestone', ...],
 *   addEntries:  [{ item: 'minecraft:diamond', count: 1, chance: 0.1, min: 1, max: 1 }, ...]
 * }
 */
async function saveLootOverride(root, tableOverride) {
  const hasLootJS = await checkLootJS(root);
  if (!hasLootJS) {
    return { ok: false, error: 'Мод LootJS не установлен. Без него правки лута не применятся. Установите LootJS.' };
  }

  const data = await loadOverrides(root);
  // чистим пустышки
  if (!tableOverride.removeEntries || !tableOverride.removeEntries.length) delete tableOverride.removeEntries;
  if (!tableOverride.addEntries || !tableOverride.addEntries.length) delete tableOverride.addEntries;

  if (!tableOverride.removeEntries && !tableOverride.addEntries) {
    delete data.tables[tableOverride.tableId];
  } else {
    data.tables[tableOverride.tableId] = tableOverride;
  }

  await saveOverrides(root, data);

  const scriptPath = path.join(root, KUBEJS_FILE);
  if (Object.keys(data.tables).length === 0) {
    try { await fsp.unlink(scriptPath); } catch {}
  } else {
    await fsp.mkdir(path.dirname(scriptPath), { recursive: true });
    await fsp.writeFile(scriptPath, generateScript(data), 'utf8');
  }

  // README один раз
  try { await fsp.access(path.join(root, KUBEJS_RM)); }
  catch {
    await fsp.writeFile(path.join(root, KUBEJS_RM), [
      '# analyzer_*.js',
      '',
      'Файлы `analyzer_recipes.js` и `analyzer_loot.js` сгенерированы приложением',
      '**Modpack Analyzer PRO**. Не редактируйте их вручную — при следующем сохранении',
      'из приложения файлы будут полностью перезаписаны.',
      '',
      'Правки хранятся в `data/recipe-overrides.json` и `data/loot-overrides.json`.',
      ''
    ].join('\n'), 'utf8');
  }

  log.info('loot-editor', 'saved', { tableId: tableOverride.tableId, total: Object.keys(data.tables).length });
  return { ok: true, path: scriptPath };
}

async function listLootOverrides(root) {
  return loadOverrides(root);
}

/* ================== KubeJS + LootJS генератор ================== */

function generateScript(data) {
  const lines = [];
  lines.push('// Auto-generated by Modpack Analyzer PRO');
  lines.push('// Do not edit manually — will be overwritten on next save from the app.');
  lines.push('// Source of truth: data/loot-overrides.json');
  lines.push('// Requires mod: LootJS');
  lines.push('');
  lines.push('LootJS.modifiers(event => {');

  for (const id of Object.keys(data.tables)) {
    const t = data.tables[id];
    lines.push('');
    lines.push('  // === ' + id + ' ===');

    // для entity используется addEntityLootModifier, для block — addBlockLootModifier
    const method = t.category === 'entity' ? 'addEntityLootModifier' : 'addBlockLootModifier';
    // LootJS принимает targetId в формате namespace:path, для блока "minecraft:stone"
    const targetId = tableIdToTarget(id);
    lines.push('  event.' + method + '(' + jsStr(targetId) + ')');

    if (t.removeEntries && t.removeEntries.length) {
      for (const item of t.removeEntries) {
        lines.push('    .removeLoot(' + jsStr(item) + ')');
      }
    }

    if (t.addEntries && t.addEntries.length) {
      for (const a of t.addEntries) {
        const count = a.min === a.max ? String(a.min || 1) : (a.min + '-' + a.max);
        const chance = a.chance !== undefined ? a.chance : 1;
        lines.push('    .addLoot(LootEntry.of(' + jsStr(a.item) + ')');
        if (count !== '1') lines.push('      .withCount(' + count + ')');
        if (chance < 1) lines.push('      .withChance(' + chance + ')');
        lines.push('    )');
      }
    }

    lines.push('    ;');
  }

  lines.push('});');
  lines.push('');
  return lines.join('\n');
}

/**
 * Из 'minecraft:blocks/stone' → 'minecraft:stone'
 * Из 'minecraft:entities/zombie' → 'minecraft:zombie'
 */
function tableIdToTarget(id) {
  const m = id.match(/^([^:]+):(?:blocks|entities|chests|gameplay)\/(.+)$/);
  if (m) return m[1] + ':' + m[2].replace(/\//g, '_');
  return id.replace(/\//g, '_');
}

function jsStr(s) {
  return "'" + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

module.exports = { checkLootJS, saveLootOverride, listLootOverrides };