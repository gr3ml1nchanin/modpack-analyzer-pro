'use strict';
const fsp  = require('fs').promises;
const path = require('path');
const log  = require('./logger');

const OVERRIDES = 'data/recipe-overrides.json';
const KUBEJS_SCRIPT = 'kubejs/server_scripts/analyzer_recipes.js';
const KUBEJS_README = 'kubejs/server_scripts/README.md';

async function checkKubeJS(root) {
  try {
    await fsp.access(path.join(root, 'kubejs'));
    return true;
  } catch {
    // Попробуем найти мод
    try {
      const mods = await fsp.readdir(path.join(root, 'mods'));
      return mods.some(f => /kubejs/i.test(f));
    } catch { return false; }
  }
}

async function loadOverrides(root) {
  const p = path.join(root, OVERRIDES);
  try {
    const raw = await fsp.readFile(p, 'utf8');
    return JSON.parse(raw);
  } catch { return { recipes: {}, removed: [] }; }
}

async function saveOverrides(root, data) {
  const p = path.join(root, OVERRIDES);
  await fsp.mkdir(path.dirname(p), { recursive: true });
  await fsp.writeFile(p, JSON.stringify(data, null, 2), 'utf8');
}

/**
 * recipe: {
 *   id,         // unique id (для override существующего) или новый `custom:name_<ts>`
 *   type,       // crafting_shaped / crafting_shapeless / smelting / ...
 *   shape?,     // ['AAA','ABA','AAA'] — только для shaped
 *   key?,       // { A: 'minecraft:cobblestone', B: '#minecraft:planks' } — для shaped
 *   ingredients?, // массив строк — для shapeless/smelting
 *   result:     // { item: 'minecraft:stone', count: 4 }
 *   group?,     // опционально
 *   originalId? // если это перезапись — id оригинала, чтобы удалить
 * }
 */
async function saveRecipe(root, recipe) {
  const kubeAvailable = await checkKubeJS(root);
  if (!kubeAvailable) {
    return { ok: false, error: 'KubeJS не установлен в сборке. Установите мод для сохранения рецептов.' };
  }

  const data = await loadOverrides(root);
  const newId = recipe.id || ('analyzer:' + slugify(recipe.result && recipe.result.item) + '_' + Date.now());
  recipe.id = newId;
  data.recipes[newId] = recipe;
  await saveOverrides(root, data);

  const script = generateKubeScript(data);
  const scriptPath = path.join(root, KUBEJS_SCRIPT);
  await fsp.mkdir(path.dirname(scriptPath), { recursive: true });
  await fsp.writeFile(scriptPath, script, 'utf8');

  // README — один раз
  const readmePath = path.join(root, KUBEJS_README);
  try { await fsp.access(readmePath); }
  catch {
      await fsp.writeFile(readmePath, [
      '# analyzer_recipes.js',
      '',
      'Этот файл сгенерирован приложением **KatAn**.',
      'Не редактируйте его вручную — при следующем сохранении из приложения',
      'файл будет полностью перезаписан.',
      '',
      'Если хотите откатить правки — откройте KatAn, раздел «Рецепты»,',
      'и удалите ненужные изменения. Или откатите вручную по data/recipe-overrides.json.',
      ''
    ].join('\n'), 'utf8');
  }

  log.info('recipe-editor', 'saved', { id: newId, total: Object.keys(data.recipes).length });
  return { ok: true, id: newId, path: scriptPath };
}

async function deleteRecipe(root, id) {
  const data = await loadOverrides(root);
  if (!data.recipes[id]) return { ok: false, error: 'Не найдено' };
  delete data.recipes[id];
  await saveOverrides(root, data);

  const scriptPath = path.join(root, KUBEJS_SCRIPT);
  if (Object.keys(data.recipes).length === 0) {
    // нет правок — удаляем файл
    try { await fsp.unlink(scriptPath); } catch {}
  } else {
    await fsp.writeFile(scriptPath, generateKubeScript(data), 'utf8');
  }
  return { ok: true };
}

async function listOverrides(root) {
  const data = await loadOverrides(root);
  return data;
}

/* ================== KubeJS генератор ================== */

function generateKubeScript(data) {
  const lines = [];
  lines.push('// Auto-generated by Modpack Analyzer PRO');
  lines.push('// Do not edit manually — will be overwritten on next save from the app.');
  lines.push('// Source of truth: data/recipe-overrides.json');
  lines.push('');
  lines.push('ServerEvents.recipes(event => {');

  for (const id of Object.keys(data.recipes)) {
    const r = data.recipes[id];
    lines.push('');
    lines.push('  // === ' + id + ' ===');

    // Удалить оригинал если это перезапись
    if (r.originalId && r.originalId !== r.id) {
      lines.push('  event.remove({ id: ' + jsStr(r.originalId) + ' })');
    }

    if (r.type === 'crafting_shaped') {
      const shape = r.shape || ['   ', '   ', '   '];
      const key = r.key || {};
      lines.push('  event.shaped(');
      lines.push('    Item.of(' + jsStr((r.result.count > 1 ? r.result.count + 'x ' : '') + r.result.item) + '),');
      lines.push('    [');
      shape.forEach(s => lines.push('      ' + jsStr(s) + ','));
      lines.push('    ],');
      lines.push('    {');
      const keys = Object.keys(key);
      keys.forEach((k, i) => {
        const v = key[k];
        lines.push('      ' + k + ': ' + jsStr(v) + (i < keys.length - 1 ? ',' : ''));
      });
      lines.push('    }');
      lines.push('  )');
    }
    else if (r.type === 'crafting_shapeless') {
      const ings = r.ingredients || [];
      lines.push('  event.shapeless(');
      lines.push('    Item.of(' + jsStr((r.result.count > 1 ? r.result.count + 'x ' : '') + r.result.item) + '),');
      lines.push('    [' + ings.map(x => jsStr(x)).join(', ') + ']');
      lines.push('  )');
    }
    else if (r.type === 'smelting' || r.type === 'blasting' || r.type === 'smoking' || r.type === 'campfire_cooking') {
      const ing = (r.ingredients || [])[0] || '';
      lines.push('  event.' + r.type + '(');
      lines.push('    ' + jsStr((r.result.count > 1 ? r.result.count + 'x ' : '') + r.result.item) + ',');
      lines.push('    ' + jsStr(ing));
      if (r.experience !== undefined) lines.push('    , ' + r.experience);
      lines.push('  )');
    }
    else if (r.type === 'stonecutting') {
      const ing = (r.ingredients || [])[0] || '';
      lines.push('  event.stonecutting(');
      lines.push('    ' + jsStr((r.result.count > 1 ? r.result.count + 'x ' : '') + r.result.item) + ',');
      lines.push('    ' + jsStr(ing));
      lines.push('  )');
    }
    else {
      lines.push('  // Неподдерживаемый тип: ' + r.type);
    }
  }

  lines.push('})');
  lines.push('');
  return lines.join('\n');
}

function jsStr(s) {
  return "'" + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}
function slugify(s) {
  return String(s || 'recipe').toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 40) || 'recipe';
}

module.exports = { checkKubeJS, saveRecipe, deleteRecipe, listOverrides, generateKubeScript };